def fetch(url: str, timeout: int = 180) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    for attempt in range(3):
        try:
            with urllib.request.urlopen(req, timeout=timeout) as resp:  # noqa: S310 (fixed hosts)
                return resp.read()
        except OSError:
            if attempt == 2:
                raise
    raise AssertionError


def primary_day(row: dict) -> str | None:
    """The calendar day the Hub files a row under (site/js/validate.js derive())."""
    d = row.get("event_date") if row.get("date_basis") == "event" else row.get("published_at")
    if not d:
        return None
    if len(d) == 10:
        return d
    t = datetime.datetime.fromisoformat(d.replace("Z", "+00:00"))
    if t.tzinfo is None:
        t = t.replace(tzinfo=datetime.timezone.utc)
    return t.astimezone(datetime.timezone.utc).date().isoformat()


def refresh() -> int:
    index_raw = fetch(HUB + "data/v7/index.json")
    index = json.loads(index_raw)
    if index.get("schema_version") != 7:
        raise SystemExit("the Hub index is not schema 7")
    shards = {s["path"]: s for s in index["shards"]}
    wanted = sorted(p for p in shards if p.startswith(("live/", "history/"))) + ["cve-index.json"]
    data, inputs = {}, [{"path": "data/v7/index.json", "bytes": len(index_raw),
                         "sha256": hashlib.sha256(index_raw).hexdigest()}]
    for p in wanted:
        raw = fetch(HUB + "data/v7/" + p)
        digest = hashlib.sha256(raw).hexdigest()
        if digest != shards[p]["sha256"] or len(raw) != shards[p]["bytes"]:
            raise SystemExit("data/v7/" + p + " does not match its index entry (the Hub published "
                             "while this ran?); run --refresh again")
        data[p] = json.loads(raw)
        inputs.append({"path": "data/v7/" + p, "bytes": len(raw), "sha256": digest})
    cve_rows = data["cve-index.json"]["rows"]
    fields = data["cve-index.json"]["fields"]
    added = {r[0]: r[fields.index("kev_date_added")] for r in cve_rows}
    live = {}
    for p in sorted(x for x in data if x.startswith("live/")):
        for r in data[p]["rows"]:
            live.setdefault(r["id"], r)
    tags = {t: collections.Counter() for t in TAG_TYPES}
    kev = {t: collections.Counter() for t in TAG_TYPES}
    for r in live.values():
        tg = r.get("tagging") or {}
        linked = r["kind"] == "kev" or tg.get("kev") is not None or any(added.get(c) for c in r.get("cves", []))
        for t in TAG_TYPES:
            for ident in {x[0] for x in tg.get(t) or []}:
                key = ident.split(":", 1)[1]
                tags[t][key] += 1
                kev[t][key] += 1 if linked else 0
    years, reporting = collections.Counter(), collections.Counter()
    for y in sorted({p[8:12] for p in data if p.startswith("history/")} |
                    {p[5:9] for p in data if p.startswith("live/") and p != "live/undated.json"}):
        seen = {}
        for p in [x for x in data if x.startswith("live/" + y + "-")] + ["history/" + y + ".json"]:
            for r in (data.get(p) or {}).get("rows", []):
                seen.setdefault(r["id"], r)
        for r in seen.values():
            d = primary_day(r)
            if d and d[:4] == y:
                years[y] += 1
                reporting[y] += r["kind"] == "reporting"
    commit = json.loads(fetch("https://api.github.com/repos/" + HUB_REPO + "/commits?path="
                              + CONTRACT_PATH + "&per_page=1"))[0]["sha"]
    contract = fetch("https://raw.githubusercontent.com/" + HUB_REPO + "/" + commit + "/" + CONTRACT_PATH)
    snap = {
        "_about": ["What the Intelligence Hub had when this snapshot was pinned, read by "
                   "scripts/build_hub_links.py to decide which On the Intelligence Hub links to write. "
                   "Written by python scripts/build_hub_links.py --refresh; do not edit.",
                   "tags: entries per vocabulary tag in the Explorer's default view (the live window, "
                   "data/v7/live/), and how many of them are linked to CISA KEV. years: entries a "
                   "#/explore?year= view lists. reporting_years: the press reporting among them. "
                   "cves: every CVE in data/v7/cve-index.json (each has a brief)."],
        "hub": {"base": HUB, "index_generated_at": index["generated_at"], "content_date": index["content_date"],
                "content_revision": index["content_revision"],
                "vocab_version": (index.get("tagging") or {}).get("vocab_version"),
                "tagger_version": (index.get("tagging") or {}).get("tagger_version"),
                "live_window": index["window"]},
        "route_contract": {"repo": HUB_REPO, "path": CONTRACT_PATH, "commit": commit,
                           "sha256": hashlib.sha256(contract).hexdigest()},
        "inputs": inputs,
        "tags": {t: {k: {"entries": tags[t][k], "kev_linked": kev[t][k]} for k in sorted(tags[t])} for t in TAG_TYPES},
        "years": {y: years[y] for y in sorted(years) if years[y]},
        "reporting_years": {y: reporting[y] for y in sorted(reporting) if reporting[y]},
        "cves": sorted({r[0] for r in cve_rows}),
    }
    probs = snapshot_problems(snap)
    if probs:
        raise SystemExit("refusing to write the snapshot: " + "; ".join(probs))
    path = os.path.join(ROOT, SNAPSHOT)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(snap, fh, indent=1, sort_keys=True, ensure_ascii=False)
        fh.write("\n")
    print("wrote " + SNAPSHOT + " (Hub index " + index["generated_at"] + ", " + str(len(live))
          + " live entries; route contract " + commit[:12] + ")")
    return 0


