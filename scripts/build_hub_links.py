    bad = json.loads(json.dumps(snap))
    bad["cves"] = ["CVE-2021-44228", "CVE-2020-1472"]
    expect("snapshot cves unsorted", snapshot_problems(bad) != [])
    vocab = [{"id": "vendor:acme", "type": "vendor", "label": "Acme", "match": ["Acme"], "library_path": "/platforms/acme.md"},
             {"id": "product:acme-gate", "type": "product", "label": "Acme Gate", "match": [], "library_path": "/platforms/acme.md"},
             {"id": "vendor:none", "type": "vendor", "label": "Nobody", "match": [], "library_path": "/platforms/none.md"},
             {"id": "actor:G0007", "type": "actor", "label": "APT28", "match": ["APT28", "Fancy Bear"], "library_path": None},
             {"id": "actor:G0016", "type": "actor", "label": "APT29", "match": ["APT29"], "library_path": None},
             {"id": "malware:S1129", "type": "malware", "label": "Akira", "match": ["Akira"], "library_path": None}]
