HUB = "https://teamstarwolf.github.io/intelligence-hub/"
HUB_REPO = "TeamStarWolf/intelligence-hub"
CONTRACT_PATH = "docs/URLS.md"
SNAPSHOT = "data/hub/tag_counts.json"
VOCAB = "data/vocab/entities.jsonl"
USER_AGENT = "teamstarwolf-library-build (+https://github.com/TeamStarWolf/TeamStarWolf)"
GENERATED_BY = "written by scripts/build_hub_links.py from data/hub/tag_counts.json; do not edit"
START = "<!-- hub-links:start (" + GENERATED_BY + ") -->"
END = "<!-- hub-links:end -->"
BLOCK_RE = re.compile(r"\n<!-- hub-links:start[^\n]*-->\n.*?<!-- hub-links:end -->\n", re.S)
MARK_RE = re.compile(r"<!-- hub-links:(?:start|end)\b")
SEP = " · "
LEAD = "On the Intelligence Hub: "
# Pages generated by other scripts: never targets, and a marker there is an error.
GENERATED = ("mitre/", "techniques/", "detections/strategies/", "scores/", "navigator/", "hubs/")
# Generated index pages outside those folders that repeat other pages' CVE ids: the case
# study timeline (scripts/build_case_study_timeline.py) lists each study's CVEs, so the
# studies themselves are the pages that name them.
GENERATED_FILES = {"case-studies/TIMELINE.md"}
CVE_RE = re.compile(r"(?<![\w-])CVE-\d{4}-\d{4,19}(?!\d)")
TAG_TYPES = ("vendor", "product", "actor", "malware")

# ----------------------------------------------------------------------------- route contract
# docs/URLS.md in the Hub repository: views, the keys each view reads, and the value checks.
VIEWS = {"explore", "today", "advisories", "kev", "research", "news", "cves", "cve", "reports",
         "sources", "data", "about"}
LIST_KEYS = ("q", "kind", "class", "event", "exp", "kev", "action", "vendor", "product", "actor",
             "malware", "sector", "region", "source", "year", "month", "range", "sort", "page", "open")
VIEW_KEYS = {"explore": LIST_KEYS, "advisories": LIST_KEYS, "research": LIST_KEYS, "news": LIST_KEYS,
             "kev": ("q", "year", "range", "sort", "page"), "cves": ("q", "kev", "action", "sort", "page"),
             "cve": (), "today": (), "reports": (), "sources": (), "data": (), "about": ()}
SLUG = re.compile(r"^[a-z0-9](?:[a-z0-9-]{0,78}[a-z0-9])?$")
ENTITY = re.compile(r"^[A-Za-z0-9](?:[A-Za-z0-9-]{0,62}[A-Za-z0-9])?$")
VALUE = {
    "kind": re.compile(r"^(?:advisory|research|reporting|incident|kev|filing|bulletin|note)$"),
    "kev": re.compile(r"^1$"), "action": re.compile(r"^1$"),
    "vendor": SLUG, "product": SLUG, "sector": SLUG, "actor": ENTITY, "malware": ENTITY,
    "year": re.compile(r"^(?:199[89]|20[0-9]{2})$"), "month": re.compile(r"^(?:0[1-9]|1[0-2])$"),
    "range": re.compile(r"^(?:3|7|30|90|365|all)$"),
}
CVE_ID = re.compile(r"^CVE-\d{4}-\d{4,19}$")
# A view's default range is left out of a canonical link, as the page itself does.
DEFAULT_RANGE = {"explore": "all", "advisories": "30", "research": "30", "news": "7", "kev": "30"}


def hub_url(view: str, ident: str | None = None, **query: str) -> str:
    """A canonical Hub link: #/<view>[/<id>]?<keys in contract order>. Raises ValueError on a
    view, key or value the contract does not allow, so a bad link never reaches a page."""
    if view not in VIEWS:
        raise ValueError("unknown Hub view " + view)
    if view == "cve":
        if not ident or not CVE_ID.match(ident):
            raise ValueError("a #/cve link needs a CVE id, got " + str(ident))
    elif ident is not None:
        raise ValueError("only #/cve takes an id")
    allowed = VIEW_KEYS[view]
    for k, v in query.items():
        if k not in allowed:
            raise ValueError("view " + view + " does not read key " + k)
        check = VALUE.get(k)
        if check is None or not check.match(v):
            raise ValueError("bad value for " + k + ": " + v)
    if "month" in query and "year" not in query:
        raise ValueError("month needs year")
    pairs = [(k, query[k]) for k in allowed if k in query and not (k == "range" and query[k] == DEFAULT_RANGE.get(view))]
    out = HUB + "#/" + view + ("/" + ident if ident else "")
    if pairs:
        out += "?" + urllib.parse.urlencode(pairs)
    return out


def md_link(label: str, url: str) -> str:
    return "[" + label.replace("[", "(").replace("]", ")") + "](" + url + ")"


# ----------------------------------------------------------------------------- inputs


def load_vocab() -> list[dict]:
    text = read_text(VOCAB)
    if text is None:
        raise SystemExit(VOCAB + ": not found (run scripts/build_vocab.py)")
    return [json.loads(line) for line in text.splitlines() if line.strip()]


def load_snapshot() -> dict:
    text = read_text(SNAPSHOT)
    if text is None:
        raise SystemExit(SNAPSHOT + ": not found (run python scripts/build_hub_links.py --refresh)")
    snap = json.loads(text)
    probs = snapshot_problems(snap)
    if probs:
        raise SystemExit(SNAPSHOT + ": " + "; ".join(probs))
    return snap


def snapshot_problems(snap: dict) -> list[str]:
    out = []
    for key in ("hub", "route_contract", "inputs", "tags", "years", "reporting_years", "cves"):
        if key not in snap:
            out.append("missing key " + key)
    if out:
        return out
    for t in TAG_TYPES:
        for k, v in (snap["tags"].get(t) or {}).items():
            if not isinstance(v, dict) or not isinstance(v.get("entries"), int) or v["entries"] < 1 \
                    or not isinstance(v.get("kev_linked"), int) or not 0 <= v["kev_linked"] <= v["entries"]:
                out.append("tags." + t + "." + k + ": entries must be a positive integer and kev_linked between 0 and entries")
    for y, n in list(snap["years"].items()) + list(snap["reporting_years"].items()):
        if not VALUE["year"].match(y) or not isinstance(n, int) or n < 1:
            out.append("years: bad row " + y)
    if snap["cves"] != sorted(set(snap["cves"])) or not all(CVE_ID.match(c) for c in snap["cves"]):
        out.append("cves: must be sorted, unique CVE ids")
    for row in snap["inputs"]:
        if not re.fullmatch(r"[0-9a-f]{64}", str(row.get("sha256", ""))):
            out.append("inputs: " + str(row.get("path")) + " has no sha256")
    return out


class Hub:
    """What the snapshot says the Hub has."""

    def __init__(self, snap: dict, vocab: list[dict]):
        self.snap = snap
        self.cves = set(snap["cves"])
        self.by_id = {r["id"]: r for r in vocab}

    def tag(self, ident: str) -> dict:
        typ, _, key = ident.partition(":")
        return (self.snap["tags"].get(typ) or {}).get(key) or {"entries": 0, "kev_linked": 0}

    def has(self, ident: str) -> bool:
        return self.tag(ident)["entries"] > 0

    def year(self, y: str) -> bool:
        return self.snap["years"].get(y, 0) > 0

    def tagged(self, types: tuple[str, ...]) -> list[dict]:
        return [r for r in self.by_id.values() if r["type"] in types and self.has(r["id"])]


def tag_link(hub: Hub, ident: str, label: str, kev: bool = False) -> str:
    typ, _, key = ident.partition(":")
    q = {typ: key}
    if kev:
        q = {"kev": "1", typ: key}
    return md_link(label, hub_url("explore", **q))


def line(parts: list[str]) -> str:
    return LEAD + SEP.join(parts)


def block(text: str) -> str:
    return START + "\n\n" + text + "\n\n" + END


# ----------------------------------------------------------------------------- page edits
# Every block is inserted as "\n" + block + "\n" at the start of a line, so BLOCK_RE (which
# takes the same text out) undoes it exactly and the base text never depends on the lines.


def strip(text: str) -> str:
    return BLOCK_RE.sub("", text)


def insert(text: str, positions: list[tuple[int, str]]) -> str:
    out, last = [], 0
    for pos, body in sorted(positions):
        if pos > 0 and text[pos - 1] != "\n" or text[pos:pos + 1] not in ("\n", ""):
            # a block must sit between a line end and a blank line, or strip() cannot undo it
            raise SystemExit("build_hub_links: no blank line at the insertion point near: "
                             + text[max(0, pos - 60):pos + 60].replace("\n", " / "))
        out.append(text[last:pos])
        out.append("\n" + block(body) + "\n")
        last = pos
    out.append(text[last:])
    return "".join(out)


HEADING_RE = re.compile(r"^(#{1,6}) +(.+?) *#*$")


def headings(text: str) -> list[tuple[int, int, str]]:
    """(level, offset after the heading line's newline, heading text), outside code fences."""
    out, pos, fence = [], 0, None
    for raw in text.split("\n"):
        nxt = pos + len(raw) + 1
        s = raw.strip()
        m = re.match(r"^(`{3,}|~{3,})", s)
        if m:
            if fence is None:
                fence = m.group(1)[0] * len(m.group(1))
            elif s.startswith(fence):
                fence = None
        elif fence is None:
            h = HEADING_RE.match(raw)
            if h:
                out.append((len(h.group(1)), min(nxt, len(text)), h.group(2)))
        pos = nxt
    return out


def section_end(text: str, hs: list, i: int) -> int:
    level = hs[i][0]
    for lv, off, _ in hs[i + 1:]:
        if lv <= level:
            return text.rfind("\n", 0, off - 1) + 1
    return len(text)


def after_content(text: str, end: int) -> int:
    """The insertion point for a block at the end of a section: right after its last line of
    content, before the blank lines and the closing '---' rule that lead to the next heading."""
    lines = text[:end].split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    while lines and lines[-1].strip() == "":
        lines.pop()
    if lines and lines[-1].strip() in ("---", "***", "___"):
        lines.pop()
        while lines and lines[-1].strip() == "":
            lines.pop()
    return min(len("\n".join(lines)) + 1, len(text))


def names_in(text: str, rows: list[dict]) -> list[dict]:
    """Vocabulary rows named in text: a label or match name of four or more characters, on
    word boundaries, case-sensitive (names are proper nouns)."""
    found = []
    for r in rows:
        for n in [r["label"]] + list(r.get("match") or []):
            if len(n) >= 4 and re.search(r"(?<![\w-])" + re.escape(n) + r"(?![\w-])", text):
                found.append(r)
                break
    return sorted(found, key=lambda r: (TAG_TYPES.index(r["type"]), r["label"].casefold(), r["id"]))


def heading_names(heading: str, rows: list[dict]) -> list[dict]:
    """Rows a heading is about: each part of 'A / B (C)' that is exactly a label or match name."""
    parts = [p.strip() for p in re.split(r"/|\(|\)", heading) if p.strip()]
    found = []
    for r in rows:
        names = {n.casefold() for n in [r["label"]] + list(r.get("match") or [])}
        if any(p.casefold() in names for p in parts):
            found.append(r)
    return sorted(found, key=lambda r: (r["label"].casefold(), r["id"]))


def entity_parts(hub: Hub, rows: list[dict]) -> list[str]:
    what = {"actor": " entries", "malware": " entries"}
    return [tag_link(hub, r["id"], r["label"] + what[r["type"]]) for r in rows]


# --- the targets


def platform_page(text: str, rel: str, hub: Hub) -> str:
    own = sorted((r for r in hub.by_id.values() if r["type"] in ("vendor", "product")
                  and r.get("library_path") == "/" + rel and hub.has(r["id"])),
                 key=lambda r: (r["type"] != "vendor", r["id"]))
    if not own:
        return text
    parts = [tag_link(hub, r["id"], r["label"] + " entries") for r in own]
    kev = next((r for r in own if hub.tag(r["id"])["kev_linked"] > 0), None)
    if kev:
        parts.append(tag_link(hub, kev["id"], kev["label"] + " entries linked to CISA KEV", kev=True))
    hs = headings(text)
    pos = len(text)
    for i, (lv, off, h) in enumerate(hs):
        if h.strip() == "Related pages":
            end = section_end(text, hs, i)
            lines = text[off:end].split("\n")
            last = off
            cur = off
            for ln in lines:
                cur_end = cur + len(ln) + 1
                if ln.startswith("- "):
                    last = min(cur_end, len(text))
                cur = cur_end
            pos = last
            break
    if pos == len(text) and not text.endswith("\n"):
        text += "\n"
        pos = len(text)
    return insert(text, [(pos, line(parts))])


def incidents_page(text: str, hub: Hub) -> str:
    people = hub.tagged(("actor", "malware"))
    pos = []
    for lv, off, h in headings(text):
        m = re.match(r"^(\d{4})(?:-(\d{4}))?: (.+)$", h)
        if lv != 3 or not m:
            continue
        first, last = int(m.group(1)), int(m.group(2) or m.group(1))
        parts = [md_link(("entries from " if y == first else "") + str(y), hub_url("explore", year=str(y)))
                 for y in range(first, last + 1) if hub.year(str(y))]
        parts += [md_link(c + " brief", hub_url("cve", c)) for c in sorted(set(CVE_RE.findall(h))) if c in hub.cves]
        parts += entity_parts(hub, names_in(m.group(3), people))
        if parts:
            pos.append((off, line(parts)))
    return insert(text, pos)


def almanac_page(text: str, hub: Hub) -> str:
    hs = headings(text)
    sec = [off for lv, off, h in hs if lv == 2 and h.strip() == "Cover year versus data window"]
    if len(sec) != 1:
        raise SystemExit("THREAT_REPORT_ALMANAC.md: expected one 'Cover year versus data window' heading")
    end_year = int(hub.snap["hub"]["content_date"][:4])
    years = [str(y) for y in range(end_year, end_year - 3, -1) if hub.snap["reporting_years"].get(str(y))]
    parts = [md_link("press reporting from the last 24 months", hub_url("explore", kind="reporting"))]
    parts += [md_link("reporting published in " + y, hub_url("explore", kind="reporting", year=y)) for y in years]
    return insert(text, [(sec[0], line(parts))])


def kev_page(text: str, hub: Hub) -> str:
    sec = [off for lv, off, h in headings(text) if lv == 2 and h.strip() == "CISA KEV catalog semantics"]
    if len(sec) != 1:
        raise SystemExit("VULNERABILITY_PRIORITIZATION_REFERENCE.md: expected one 'CISA KEV catalog semantics' heading")
    parts = [md_link("KEV additions in the last 30 days", hub_url("kev")),
             md_link("every KEV entry by date added", hub_url("kev", range="all")),
             md_link("entries linked to CISA KEV", hub_url("explore", kev="1")),
             md_link("KEV CVEs in the CVE register", hub_url("cves", kev="1"))]
    return insert(text, [(sec[0], line(parts))])


def cve_mentions(hub: Hub, files: list[str]) -> dict[str, list[str]]:
    """CVE -> the hand-written pages that name it, for every CVE the Hub has a brief for."""
    out = collections.defaultdict(set)
    for f in files:
        if not f.endswith(".md") or f.startswith(GENERATED) or f in GENERATED_FILES                 or os.path.basename(f).startswith("_"):
            continue
        text = strip(read_text(f) or "")
        for c in set(CVE_RE.findall(text)):
            if c in hub.cves:
                out[c].add(f)
    return {c: sorted(v) for c, v in out.items()}


def cve_key(c: str) -> tuple[int, int]:
    _, y, n = c.split("-")
    return int(y), int(n)


def cve_page(text: str, hub: Hub, mentions: dict[str, list[str]], titles: dict[str, str]) -> str:
    hs = headings(text)
    idx = [i for i, (lv, off, h) in enumerate(hs) if lv == 2 and re.match(r"^9\. Notable CVEs", h)]
    if len(idx) != 1:
        raise SystemExit("CVE_REFERENCE.md: expected one '## 9. Notable CVEs ...' heading")
    i = idx[0]
    pos = [(hs[i][1], line([md_link("the CVE register", hub_url("cves")),
                            md_link("KEV additions in the last 30 days", hub_url("kev"))]))]
    end = section_end(text, hs, i)
    for lv, off, h in hs[i + 1:]:
        if off > end:
            break
        m = re.match(r"^(CVE-\d{4}-\d{4,19})\b", h)
        if lv == 3 and m and m.group(1) in hub.cves:
            pos.append((off, line([md_link(m.group(1) + " brief", hub_url("cve", m.group(1)))])))
    rows = ["CVEs the library discusses that the Hub also tracks, each with its brief on the Hub "
            "and the pages here that name it:", "",
            "| CVE | Named in |", "|---|---|"]
    for c in sorted(mentions, key=cve_key):
        pages = ", ".join(md_link(titles.get(f, f), "/" + f) for f in mentions[c])
        rows.append("| " + md_link(c, hub_url("cve", c)) + " | " + pages + " |")
    pos.append((after_content(text, end), "\n".join(rows)))
    return insert(text, pos)


def entity_page(text: str, hub: Hub, types: tuple[str, ...]) -> str:
    """The line goes at the end of the profile under the heading (profiles open with a list
    right under the heading, so there is no blank line to hold it there)."""
    rows = hub.tagged(types)
    hs = headings(text)
    pos = []
    for i, (lv, off, h) in enumerate(hs):
        if lv < 3:
            continue
        found = heading_names(h, rows)
        if found:
            pos.append((after_content(text, section_end(text, hs, i)), line(entity_parts(hub, found))))
    return insert(text, pos)


# ----------------------------------------------------------------------------- build


TARGETS = ("NOTABLE_INCIDENTS.md", "THREAT_REPORT_ALMANAC.md", "CVE_REFERENCE.md",
           "VULNERABILITY_PRIORITIZATION_REFERENCE.md", "THREAT_ACTORS.md", "MALWARE_FAMILIES.md")


def title_of(rel: str) -> str:
    for ln in (read_text(rel) or "").split("\n"):
        m = re.match(r"^# +(.+?) *#*$", ln)
        if m:
            # Drop emphasis and code markers; an underscore inside a word (mod_copy) is text.
            return re.sub(r"(?<![A-Za-z0-9])_+|_+(?![A-Za-z0-9])", "", re.sub(r"[*`]", "", m.group(1))).strip()
    return rel


def lf(text: str) -> tuple[str, str]:
    eol = "\r\n" if "\r\n" in text else "\n"
    return text.replace("\r\n", "\n"), eol


def build(hub: Hub, files: list[str]) -> dict[str, str]:
    """Every target file's text with fresh lines (LF), from its base text."""
    out = {}
    plats = sorted(f for f in files if f.startswith("platforms/") and f.endswith(".md")
                   and f != "platforms/README.md" and not os.path.basename(f).startswith("_"))
    mentions = cve_mentions(hub, files)
    titles = {f: title_of(f) for fs in mentions.values() for f in fs}
    for rel in plats + list(TARGETS):
        cur = read_text(rel)
        if cur is None:
            raise SystemExit(rel + ": not found")
        base = strip(lf(cur)[0])
        if rel.startswith("platforms/"):
            new = platform_page(base, rel, hub)
        elif rel == "NOTABLE_INCIDENTS.md":
            new = incidents_page(base, hub)
        elif rel == "THREAT_REPORT_ALMANAC.md":
            new = almanac_page(base, hub)
        elif rel == "CVE_REFERENCE.md":
            new = cve_page(base, hub, mentions, titles)
        elif rel == "VULNERABILITY_PRIORITIZATION_REFERENCE.md":
            new = kev_page(base, hub)
        elif rel == "THREAT_ACTORS.md":
            new = entity_page(base, hub, ("actor",))
        else:
            new = entity_page(base, hub, ("malware",))
        out[rel] = new
    return out


def stray_markers(files: list[str], targets: set[str]) -> list[str]:
    out = []
    for f in files:
        if f.endswith(".md") and f not in targets:
            text = read_text(f) or ""
            if MARK_RE.search(text):
                out.append(f + ": has a hub-links marker but is not a build_hub_links.py target")
    return out


def run(check: bool) -> int:
    files = tracked_files()
    hub = Hub(load_snapshot(), load_vocab())
    gen = build(hub, files)
    probs = stray_markers(files, set(gen))
    changed = []
    for rel, new in gen.items():
        cur = read_text(rel) or ""
        text, eol = lf(cur)
        if text != new:
            changed.append(rel)
            if not check:
                with open(os.path.join(ROOT, rel), "w", encoding="utf-8", newline="") as fh:
                    fh.write(new.replace("\n", eol))
                print("wrote " + rel)
    lines = sum(new.count(START) for new in gen.values())
    pages = sum(1 for new in gen.values() if START in new)
    if check:
        probs += [rel + ": the On the Intelligence Hub lines are stale; run python scripts/build_hub_links.py"
                  for rel in changed]
        if probs:
            print("FAIL: Hub links (data/hub/tag_counts.json, data/vocab/entities.jsonl):")
            for p in probs:
                print("  - " + p)
            return 1
        print("OK: " + str(lines) + " On the Intelligence Hub blocks on " + str(pages)
              + " pages match the pinned Hub snapshot (" + hub.snap["hub"]["index_generated_at"] + ")")
        return 0
    for p in probs:
        print("WARNING: " + p)
    print(str(lines) + " blocks on " + str(pages) + " pages")
    return 1 if probs else 0


