#!/usr/bin/env python3
"""Write the "On the Intelligence Hub" lines that link library pages to Hub views.

Each line sits between `<!-- hub-links:start ... -->` and `<!-- hub-links:end -->`
markers and is written by this script only. It goes on:

    platforms/*.md                 after the Related pages list, for a page whose vendor
                                   or product (the vocabulary row whose library_path is
                                   the page) has entries on the Hub
    NOTABLE_INCIDENTS.md           under each "### YYYY: ..." heading: that year on the
                                   Hub, plus a named CVE, threat actor or malware family
                                   when the Hub has it
    THREAT_REPORT_ALMANAC.md       once, under "Cover year versus data window"
    CVE_REFERENCE.md               under section 9 and each of its "### CVE-..." headings
                                   the Hub has a brief for, and a table at the end of
                                   section 9 of every CVE the hand-written pages discuss
                                   that the Hub also tracks
    VULNERABILITY_PRIORITIZATION_REFERENCE.md
                                   once, under "CISA KEV catalog semantics"
    THREAT_ACTORS.md               under each heading that names a threat actor with
                                   Hub entries
    MALWARE_FAMILIES.md            under each heading that names a malware family with
                                   Hub entries

Inputs (nothing in a line is typed by hand):
    data/vocab/entities.jsonl      the shared vocabulary (ids, labels, names, the page
                                   each vendor and product belongs to)
    data/hub/tag_counts.json       a pinned snapshot of the Hub: entries per vocabulary
                                   tag in the Explorer's live window, KEV-linked entries
                                   per tag, entries per year, press reporting per year,
                                   and the CVEs with a brief. --refresh rewrites it from
                                   the live Hub (data/v7/index.json and the shards it
                                   lists, each checked against its SHA-256 in the index)
    the Hub route contract         docs/URLS.md in TeamStarWolf/intelligence-hub; the
                                   views and query keys below follow it, and --refresh
                                   records the commit and SHA-256 of the copy it read

A link is written only when the snapshot shows the Hub view is not empty. Counts stay in
the snapshot; the lines carry none, so a Hub update never makes a page wrong.

Usage:
    python scripts/build_hub_links.py              # write the lines from the snapshot
    python scripts/build_hub_links.py --check      # exit 1 when a line is stale or missing
    python scripts/build_hub_links.py --self-test  # planted cases (routes, markers, matching)
    python scripts/build_hub_links.py --refresh    # re-pin the snapshot from the live Hub
"""
