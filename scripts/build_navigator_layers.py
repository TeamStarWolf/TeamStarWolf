def version_cell(layer: dict) -> str:
    dom = layer.get("domain")
    if dom in ("enterprise-attack", "ics-attack", "mobile-attack"):
        return f"ATT&CK v{layer['versions']['attack']}"
    if dom == "atlas-atlas":
        return f"ATLAS data {meta_get(layer, 'atlas_data_version')}"
    if dom == "f3-financial":
        return f"F3 v{meta_get(layer, 'f3_stix_version')}"
    return str(dom)


def load_link(path: str, layer: dict) -> str:
    if layer.get("domain") == "atlas-atlas":
        return "[ATLAS Navigator](https://mitre-atlas.github.io/atlas-navigator/)"
    return f"[ Navigator]({NAVIGATOR_URL}{path})"


