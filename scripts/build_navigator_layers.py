#!/usr/bin/env python3
"""
TeamStarWolf ATT&CK Navigator layers: generate, normalize to ATT&CK v19.2, and index.

    navigator/teamstarwolf_vendor_coverage.json   GENERATED from data/attack/technique_profiles.jsonl
    navigator/stages/*.json                       curated selections, NORMALIZED in place
    navigator/vendors/*.json                      curated selections, NORMALIZED in place
    navigator/library-layers/*.json               curated selections, NORMALIZED in place
    navigator/index.md                            GENERATED from the layer files + CATALOG below

The analytics layers (navigator/analytics/) are generated by scripts/build_priority_gaps.py.
The ATLAS (navigator/ai/) and F3 (navigator/fraud/) layers are vendored from MITRE in their
own Navigator domains; this script indexes them but never rewrites them.

Usage:
    python scripts/build_navigator_layers.py           # rewrite the files above
    python scripts/build_navigator_layers.py --check   # exit 1 if any committed file is stale

Normalizing a curated layer is idempotent (a normalized layer is a fixed point), so --check
also proves that no curated layer has drifted away from the v19.2 data:

  * versions -> {"attack": "19", "navigator": "4.9", "layer": "4.5"} (scripts/build_priority_gaps.py).
  * A techniqueID that ATT&CK v19 revoked is re-keyed to its live successor through
    data/attack/superseded_by.jsonl (scripts/attack_ids.py, followed transitively); the entry
    comment records the predecessor. A deprecated id, or an id that is not an Enterprise
    technique at all (e.g. a Mobile id), is dropped.
  * A tactic the technique does not have in v19.2 is replaced from the technique's tactics in
    data/attack/technique_profiles.jsonl: the retired defense-evasion becomes whichever of its
    successors (stealth, defense-impairment) the technique has, any other misplacement (e.g.
    T1619 under collection, T1574 under persistence) becomes all of the technique's tactics.
    A layer whose tactic_policy metadata says each technique is shown under all its tactics
    is expanded to exactly those tactics.
  * (techniqueID, tactic) entries that a re-key makes identical are merged: the highest score
    is kept and the distinct comments are joined.
  * filters.platforms is mapped onto the ATT&CK v19.2 platform vocabulary (Network ->
    Network Devices, Azure AD -> Identity Provider, Office 365 / Google Workspace -> Office
    Suite, Cloud -> IaaS + SaaS + Office Suite + Identity Provider), and extended with the
    platforms of any scored technique the filter would otherwise hide (e.g. PRE).
  * The techniques_scored / technique_tactic_entries metadata are recomputed and an
    attack_version metadata entry states the baseline.

The full-stack control-depth layer is regenerated from scratch: one entry per (live
technique, v19.2 tactic) for every technique with at least one NIST 800-53 R5 control in
the profiles (CTID mappings on revoked ids are already carried forward to the successor
there), score = number of distinct controls. Output is byte-for-byte deterministic.
"""

