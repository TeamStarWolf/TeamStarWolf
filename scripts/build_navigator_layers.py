def full_stack(ids: AttackIds) -> tuple[dict, dict]:
    profiles = ids.profiles["enterprise"]
    entries, controls, pairs, platforms = [], set(), 0, set()
    scored = 0
    for tid in sorted(ids.live["enterprise"]):
        p = profiles[tid]
        platforms.update(p.get("platforms") or [])
        ctl = sorted(set(p.get("nist_800_53_controls") or []))
        if int(p.get("nist_control_count") or 0) != len(ctl):
            fail(f"{tid}: nist_control_count is {p.get('nist_control_count')} but "
                 f"nist_800_53_controls holds {len(ctl)} - re-run scripts/build_control_rollup.py")
        if not ctl:
            continue
        tactics = p.get("tactics") or []
        bad = [t for t in tactics if t not in TACTIC_ORDER]
        if bad or not tactics:
            fail(f"{tid}: tactics {tactics} are not ATT&CK v{ATTACK_VERSION} Enterprise tactics")
        scored += 1
        controls.update(ctl)
        pairs += len(ctl)
        fam = Counter(c.split("-")[0] for c in ctl)
        top = ", ".join(f"{f} ({n})" for f, n in sorted(fam.items(), key=lambda kv: (-kv[1], kv[0]))[:4])
        comment = f"{plural(len(ctl), 'NIST 800-53 R5 control')} map to this technique. Top families: {top}."
        via = p.get("nist_800_53_controls_via_revoked") or {}
        if via:
            comment += (" Includes CTID mappings carried forward from revoked "
                        f"{', '.join(sorted(via))} (data/attack/superseded_by.jsonl).")
        for tac in sorted(tactics, key=TACTIC_ORDER.get):
            entries.append({"techniqueID": tid, "tactic": tac, "score": len(ctl), "comment": comment})
    if not entries:
        fail("no live technique has a NIST 800-53 control in data/attack/technique_profiles.jsonl")
    entries.sort(key=lambda e: (-e["score"], e["techniqueID"], TACTIC_ORDER[e["tactic"]]))
    smax = max(e["score"] for e in entries)
    v = ATTACK_VERSION
    out = {
        "name": "TeamStarWolf - NIST 800-53 R5 Control Depth",
        "versions": dict(NAVIGATOR_VERSIONS),
        "domain": "enterprise-attack",
        "description": (
            f"The {scored} live ATT&CK Enterprise v{v} techniques with at least one NIST 800-53 R5 "
            "control mapping, scored by control depth: the number of distinct NIST controls that map "
            "to the technique via the CTID Mappings Explorer (NIST 800-53 R5 to ATT&CK v16.1). A "
            "mapping published against an id that ATT&CK v19 revoked is carried forward to the live "
            "successor (data/attack/superseded_by.jsonl). Higher score = more controls available to "
            "mitigate the technique; low scores flag techniques with thin framework coverage that "
            "warrant compensating detection or design controls. Control depth is not vendor or "
            "deployed coverage. Each technique is shown under all of its v19.2 tactics. Source: "
            f"data/attack/technique_profiles.jsonl (nist_800_53_controls). Generated by {GENERATED_BY}."),
        "filters": {"platforms": [x for x in PLATFORM_ORDER if x in platforms]},
    }
    out.update(json.loads(json.dumps(FULL_STACK_CHROME)))
    out["gradient"] = {"colors": GREENS, "minValue": 1, "maxValue": smax}
    out["legendItems"] = [
        {"label": "1-9 controls: thin framework coverage (prioritize compensating controls)", "color": GREENS[0]},
        {"label": "10-19 controls: moderate coverage", "color": GREENS[1]},
        {"label": "20+ controls: deep control coverage", "color": GREENS[2]},
    ]
    out["metadata"] = [{"name": k, "value": val} for k, val in (
        ("source", f"CTID Mappings Explorer - NIST 800-53 R5 to ATT&CK v16.1, carried forward to "
                   f"ATT&CK Enterprise v{v}"),
        ("mapping_url", CTID_URL),
        ("attack_version", f"MITRE ATT&CK Enterprise v{v}"),
        ("techniques_scored", str(scored)),
        ("technique_tactic_entries", str(len(entries))),
        ("nist_controls", str(len(controls))),
        ("technique_control_pairs", str(pairs)),
        ("generated_by", GENERATED_BY),
    )]
    out.update(json.loads(json.dumps(FULL_STACK_TAIL)))
    out["techniques"] = entries
    stats = {"techniques": scored, "controls": len(controls), "pairs": pairs, "max": smax}
    return out, stats


# --------------------------------------------------------------------------- normalize
def meta_get(layer: dict, name: str):
    for m in layer.get("metadata") or []:
        if m.get("name") == name:
            return m.get("value")
    return None


def meta_set(layer: dict, name: str, value: str) -> None:
    md = layer.setdefault("metadata", [])
    for m in md:
        if m.get("name") == name:
            m["value"] = value
            return
    md.append({"name": name, "value": value})


def map_platforms(platforms: list[str]) -> list[str]:
    out: list[str] = []
    for p in platforms:
        for q in PLATFORM_MAP.get(p, (p,)):
            if q not in out:
                out.append(q)
    unknown = [p for p in out if p not in PLATFORM_ORDER]
    if unknown:
        fail(f"filters.platforms {unknown} are not ATT&CK v{ATTACK_VERSION} Enterprise platforms "
             f"and have no mapping in PLATFORM_MAP")
    return out


def merge_into(kept: dict, dup: dict) -> None:
    if isinstance(dup.get("score"), (int, float)):
        if not isinstance(kept.get("score"), (int, float)) or dup["score"] > kept["score"]:
            kept["score"] = dup["score"]
    a, b = kept.get("comment") or "", dup.get("comment") or ""
    if b and b not in a.split(" | "):
        kept["comment"] = f"{a} | {b}" if a else b


def normalize(rel: str, layer: dict, ids: AttackIds, log: list[str]) -> dict:
    if layer.get("domain") != "enterprise-attack":
        fail(f"{rel}: curated layers must be enterprise-attack, found {layer.get('domain')!r}")
    profiles = ids.profiles["enterprise"]
    policy_all = (meta_get(layer, "tactic_policy") or "").startswith("Each selected technique is shown under all tactics")

    # 1. re-key revoked ids, drop ids that are not live Enterprise techniques
    rekeyed = []
    for e in layer.get("techniques") or []:
        tid = e["techniqueID"]
        state, succ = ids.status(tid, "enterprise")
        if state == "live":
            rekeyed.append(dict(e))
            continue
        if state == "revoked":
            n = dict(e)
            n["techniqueID"] = succ
            note = (f"(Re-keyed from {tid}, which ATT&CK v19 revoked in favour of {succ}; "
                    "data/attack/superseded_by.jsonl.)")
            n["comment"] = f"{n['comment']} {note}" if n.get("comment") else note
            rekeyed.append(n)
            log.append(f"{rel}: {tid} -> {succ} (revoked)")
            continue
        log.append(f"{rel}: dropped {tid} ({state}: not a live ATT&CK Enterprise technique)")

    # 2. tactics: keep valid ones, replace invalid ones by the profile tactics
    expanded = []
    for e in rekeyed:
        tac = e.get("tactic")
        valid = sorted(profiles[e["techniqueID"]].get("tactics") or [], key=TACTIC_ORDER.get)
        if tac is None or tac in valid:
            expanded.append(e)
            continue
        # the retired defense-evasion maps to whichever of its successors the technique has
        targets = [t for t in valid if t in RETIRED_TACTICS.get(tac, ())] or valid
        log.append(f"{rel}: {e['techniqueID']} tactic {tac} -> {', '.join(targets)}")
        for t in targets:
            n = dict(e)
            n["tactic"] = t
            expanded.append(n)

    # 3. tactic_policy "all tactics": every technique under exactly its profile tactics
    if policy_all:
        first: dict[str, dict] = {}
        for e in expanded:
            first.setdefault(e["techniqueID"], e)
        have = {(e["techniqueID"], e.get("tactic")) for e in expanded}
        out = []
        for e in expanded:
            out.append(e)
            if first[e["techniqueID"]] is e:
                for t in sorted(profiles[e["techniqueID"]].get("tactics") or [], key=TACTIC_ORDER.get):
                    if (e["techniqueID"], t) not in have:
                        n = dict(e)
                        n["tactic"] = t
                        out.append(n)
                        have.add((e["techniqueID"], t))
                        log.append(f"{rel}: {e['techniqueID']} also shown under {t} (tactic_policy)")
        expanded = out

    # 4. merge duplicate (techniqueID, tactic) entries
    merged: dict[tuple, dict] = {}
    for e in expanded:
        key = (e["techniqueID"], e.get("tactic"))
        if key in merged:
            merge_into(merged[key], e)
            log.append(f"{rel}: merged duplicate {key[0]} / {key[1]}")
        else:
            merged[key] = e
    techniques = list(merged.values())

    out = {}
    for k, v in layer.items():
        if k == "versions":
            out[k] = dict(NAVIGATOR_VERSIONS)
        elif k == "techniques":
            out[k] = techniques
        else:
            out[k] = v
    if "filters" in out and "platforms" in (out["filters"] or {}):
        out["filters"] = dict(out["filters"])
        plats = map_platforms(out["filters"]["platforms"])
        # a scored technique none of whose platforms is selected would be hidden: select them
        for e in techniques:
            tp = profiles[e["techniqueID"]].get("platforms") or []
            if not set(tp) & set(plats):
                add = [x for x in PLATFORM_ORDER if x in tp and x not in plats]
                plats += add
                log.append(f"{rel}: platforms filter + {', '.join(add)} (else {e['techniqueID']} is hidden)")
        out["filters"]["platforms"] = plats
    if meta_get(out, "techniques_scored") is not None:
        meta_set(out, "techniques_scored", str(len({e["techniqueID"] for e in techniques})))
    if meta_get(out, "technique_tactic_entries") is not None:
        meta_set(out, "technique_tactic_entries", str(len(techniques)))
    meta_set(out, "attack_version", ATTACK_VERSION_NOTE)
    return out


def curated_files() -> list[str]:
    out = []
    for d in CURATED_DIRS:
        for p in sorted((ROOT / d).glob("*.json")):
            rel = p.relative_to(ROOT).as_posix()
            if rel != LIBRARY_INDEX:
                out.append(rel)
    return out


