# --------------------------------------------------------------------------- driver
def all_layers() -> dict[str, dict]:
    out = {}
    for p in sorted((ROOT / "navigator").rglob("*.json")):
        rel = p.relative_to(ROOT).as_posix()
        d = json.loads(read_text(rel))
        if isinstance(d, dict) and isinstance(d.get("techniques"), list):
            out[rel] = d
    return out


def compute(log: list[str]) -> dict[str, str]:
    ids = AttackIds(ROOT)
    files: dict[str, str] = {}
    fs_layer, fs = full_stack(ids)
    files[FULL_STACK] = dump_json(fs_layer)
    for rel in curated_files():
        files[rel] = dump_json(normalize(rel, json.loads(read_text(rel)), ids, log))
    layers = all_layers()
    layers.update({rel: json.loads(text) for rel, text in files.items()})
    files[INDEX_MD] = render_index(layers, fs)
    return files


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true",
                    help="write nothing; exit 1 if any committed output differs")
    ap.add_argument("-v", "--verbose", action="store_true", help="print each normalization")
    args = ap.parse_args()
    log: list[str] = []
    files = compute(log)
    if args.verbose or args.check:
        for line in log:
            print(line)
    if args.check:
        stale = [rel for rel, text in files.items()
                 if not (ROOT / rel).is_file() or read_text(rel) != text]
        if stale:
            print(f"STALE: {', '.join(stale)} - run python {GENERATED_BY}")
            sys.exit(1)
        print(f"OK: {len(files)} Navigator files match the data (full-stack layer, "
              f"{len(files) - 2} curated layers, index)")
        return
    for rel, text in files.items():
        p = ROOT / rel
        with open(p, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print(f"Written: {len(files)} files ({len(log)} normalization changes)")


if __name__ == "__main__":
    main()
